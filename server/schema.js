'use strict';

const { STOCK_DEFINITION } = require('./stock');

function schemaFor(dialect) {
  const pg = dialect === 'postgres';
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  // A uniform UTC ISO string preserves API shape and ordering when migrating from SQLite.
  const utcNow = pg
    ? `(to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`
    : `(strftime('%Y-%m-%dT%H:%M:%fZ','now'))`;
  return `
CREATE TABLE IF NOT EXISTS orders (
  id            ${id},
  ref           TEXT UNIQUE,
  legacy_id     TEXT,
  customer_name TEXT NOT NULL,
  phone         TEXT NOT NULL,
  address       TEXT,
  product_title TEXT NOT NULL,
  product_image TEXT,
  price         TEXT,
  service_type  TEXT DEFAULT 'شراء',
  device        TEXT,
  status        TEXT DEFAULT 'جديد',
  note          TEXT,
  source        TEXT DEFAULT 'site',
  created_at    TEXT NOT NULL DEFAULT ${utcNow},
  updated_at    TEXT NOT NULL DEFAULT ${utcNow}
);
CREATE INDEX IF NOT EXISTS idx_orders_status    ON orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_created   ON orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_updated   ON orders(updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_legacy    ON orders(legacy_id);

CREATE TABLE IF NOT EXISTS maintenance (
  id            ${id},
  ref           TEXT UNIQUE,
  legacy_id     TEXT,
  name          TEXT NOT NULL,
  phone         TEXT NOT NULL,
  device        TEXT,
  description   TEXT,
  fault_images  TEXT DEFAULT '[]',
  address       TEXT,
  status        TEXT DEFAULT 'جديد',
  note          TEXT,
  source        TEXT DEFAULT 'site',
  created_at    TEXT NOT NULL DEFAULT ${utcNow},
  updated_at    TEXT NOT NULL DEFAULT ${utcNow}
);
CREATE INDEX IF NOT EXISTS idx_maint_status  ON maintenance(status);
CREATE INDEX IF NOT EXISTS idx_maint_created ON maintenance(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_maint_legacy  ON maintenance(legacy_id);

CREATE TABLE IF NOT EXISTS products (
  id          ${id},
  legacy_id   TEXT,
  title       TEXT NOT NULL,
  price       TEXT,
  old_price   TEXT,
  discount_percent INTEGER DEFAULT 0,
  category    TEXT,
  image       TEXT,
  description TEXT,
  active      INTEGER DEFAULT 1,
  stock_quantity ${STOCK_DEFINITION},
  created_at  TEXT NOT NULL DEFAULT ${utcNow},
  updated_at  TEXT NOT NULL DEFAULT ${utcNow}
);
CREATE INDEX IF NOT EXISTS idx_products_legacy ON products(legacy_id);

CREATE TABLE IF NOT EXISTS visits (
  day   TEXT PRIMARY KEY,
  count INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS visitor_logs (
  id          ${id},
  ip          TEXT NOT NULL,
  page        TEXT,
  referrer    TEXT,
  user_agent  TEXT,
  device      TEXT,
  created_at  TEXT NOT NULL DEFAULT ${utcNow}
);
CREATE INDEX IF NOT EXISTS idx_visitor_logs_created ON visitor_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_visitor_logs_ip ON visitor_logs(ip);

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS ref_counters (
  prefix TEXT PRIMARY KEY,
  value INTEGER NOT NULL
);
${pg ? `
CREATE TABLE IF NOT EXISTS uploaded_images (
  name TEXT PRIMARY KEY,
  content_type TEXT NOT NULL,
  contents BYTEA NOT NULL
);` : ''}
`;
}

async function ensureSchema(db) {
  if (db.dialect === 'sqlite') {
    await db.exec('PRAGMA journal_mode = WAL; PRAGMA synchronous = FULL; PRAGMA busy_timeout = 5000; PRAGMA foreign_keys = ON;');
  }
  await db.transaction(async tx => {
    if (db.dialect === 'postgres') await tx.get('SELECT pg_advisory_xact_lock(41803721)');
    await tx.exec(schemaFor(db.dialect));
    const columns = db.dialect === 'postgres'
      ? await tx.all(`SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'products'`)
      : await tx.all('PRAGMA table_info(products)');
    const names = new Set(columns.map(c => c.name));
    if (!names.has('old_price')) await tx.exec('ALTER TABLE products ADD COLUMN old_price TEXT');
    if (!names.has('discount_percent')) await tx.exec('ALTER TABLE products ADD COLUMN discount_percent INTEGER DEFAULT 0');
    if (!names.has('stock_quantity')) await tx.exec('ALTER TABLE products ADD COLUMN stock_quantity ' + STOCK_DEFINITION);
  });
}
module.exports = { schemaFor, ensureSchema };
